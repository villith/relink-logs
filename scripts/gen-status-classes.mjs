/**
 * Emits the two halves of the status-class provenance edge from one source of
 * truth (the Ghidra-derived CSV, see the 2026-08-05 status-rtti plan Task 2):
 *
 *   src-hook/src/hooks/status_class_table.rs  vtable RVA -> class-name hash
 *   src-tauri/assets/status-classes.json      hash -> { class, name }
 *
 * The vtable RVA is the half a game patch moves, so it stays inside the hook
 * and never reaches a log. The hash is derived from the class NAME, which is
 * stable across patches — so an old log can fail to resolve, but can never
 * resolve to the WRONG class.
 *
 * Usage: node scripts/gen-status-classes.mjs <path to status_vtables.csv>
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { gameXxhash32 } from "./gbfr-hash.mjs";
import { isNameless, prettifyClassName } from "./status-class-name.mjs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

/** Parses the two-column CSV Task 2 produces. */
export const parseCsv = (text) =>
  text
    .split(/\r?\n/)
    .slice(1)
    .filter((line) => line.trim() !== "")
    .map((line) => {
      const [rva, className] = line.split(",");
      return { vtable_rva: Number(rva), class: className.trim() };
    });

/** Guards the reserved "known but nameless" sentinel (hash 0): a NAMED class
 * must never land there, or the hook and app tables would silently disagree
 * about what 0 means. Astronomically unlikely at 32 bits — this cannot
 * realistically fire on real data — but it is one line, and it turns silent
 * corruption into a loud one, which is how the rest of this codebase treats
 * "cannot happen" cases.
 */
export const assertHashNotSentinel = (className, hash) => {
  if (hash === 0) {
    throw new Error(`${className} hashes to 0, which is the reserved nameless sentinel`);
  }
};

/** CSV rows -> { hook: [{rva, hash, class}], app: { hash: {class, name} } }. */
export const buildTables = (rows) => {
  const seen = new Map();
  const hook = [];
  const app = {};
  for (const row of rows) {
    const previous = seen.get(row.vtable_rva);
    if (previous !== undefined) {
      throw new Error(
        `duplicate vtable rva 0x${row.vtable_rva.toString(16)}: ${previous} and ${row.class}`
      );
    }
    seen.set(row.vtable_rva, row.class);
    // Hash 0 is the reserved "known but nameless" marker, so a base class is
    // still present in the table — the hook can tell "I know this vtable and it
    // says nothing" apart from "I have never seen this vtable".
    const nameless = isNameless(row.class);
    // gameXxhash32 returns eight lowercase hex digits as a STRING (it mirrors
    // the lang-file hash keys); parseInt, not `>>> 0`, is what turns that into
    // the u32 the hook table and the JSON key both need.
    const hash = nameless ? 0 : parseInt(gameXxhash32(row.class), 16);
    if (!nameless) assertHashNotSentinel(row.class, hash);
    hook.push({ rva: row.vtable_rva, hash, class: row.class });
    if (!nameless) app[String(hash)] = { class: row.class, name: prettifyClassName(row.class) };
  }
  hook.sort((a, b) => a.rva - b.rva);
  return { hook, app };
};

export const renderRust = (hook) =>
  `//! GENERATED by scripts/gen-status-classes.mjs — do not hand-edit.
//!
//! \`vtable RVA -> class-name hash\` for the \`StatusBase\` family. Sorted by RVA
//! so the lookup can binary-search, exactly as \`summon.rs\` does for its own
//! vtable set. Hash 0 means a class that names no mechanism (\`StatusBase\` and
//! friends): known, and deliberately nameless.
//!
//! Regenerate after a game patch — the RVAs move, the hashes do not.

pub const STATUS_CLASS_TABLE: &[(usize, u32)] = &[
${hook.map((row) => `    (${`0x${row.rva.toString(16).toUpperCase()}`}, ${row.hash}), // ${row.class}`).join("\n")}
];
`;

const main = () => {
  const source = process.argv[2];
  if (!source) {
    console.error("usage: node scripts/gen-status-classes.mjs <status_vtables.csv>");
    process.exit(1);
  }
  if (!existsSync(source)) {
    console.error(`[gen] missing ${source} — run the Ghidra enumeration first (plan Task 2)`);
    process.exit(1);
  }
  const { hook, app } = buildTables(parseCsv(readFileSync(source, "utf8")));
  writeFileSync(path.join(ROOT, "src-hook", "src", "hooks", "status_class_table.rs"), renderRust(hook));
  writeFileSync(
    path.join(ROOT, "src-tauri", "assets", "status-classes.json"),
    JSON.stringify(app, null, 2) + "\n"
  );
  console.log(`[gen] ${hook.length} vtables, ${Object.keys(app).length} named classes`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
